"""SQLAlchemy ORM models.

Two project-defining rules are enforced by the **database**, not by application code,
because a rule that lives only in Python is one refactor away from being untrue:

* ``ConsentRecord.eligible_for_training`` is a generated column. A record belonging to
  a minor, or without an explicit research opt-in, can never be selected into a
  training set -- there is no application path that sets the flag directly (Q-2).
* ``Document.originals_expire_at`` is NOT NULL, so every upload carries a retention
  deadline from the moment it exists (Q-5).
"""

from __future__ import annotations

import datetime as dt
import enum
import uuid

from sqlalchemy import (
    BigInteger,
    Boolean,
    CheckConstraint,
    Computed,
    DateTime,
    Enum,
    ForeignKey,
    Index,
    Integer,
    String,
    Text,
    UniqueConstraint,
    func,
)
from sqlalchemy.dialects.postgresql import INET, JSONB, UUID
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column, relationship


class Base(DeclarativeBase):
    pass


def _uuid_pk() -> Mapped[uuid.UUID]:
    return mapped_column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)


class DocumentStatus(enum.StrEnum):
    PENDING = "pending"
    PROCESSING = "processing"
    COMPLETE = "complete"
    FAILED = "failed"
    DELETED = "deleted"


class LawfulBasis(enum.StrEnum):
    CONSENT = "consent"
    CONTRACT = "contract"
    LEGITIMATE_INTEREST = "legitimate_interest"


class User(Base):
    __tablename__ = "users"

    id: Mapped[uuid.UUID] = _uuid_pk()
    email: Mapped[str] = mapped_column(String(320), unique=True, nullable=False)
    # Argon2id encoded hash (C-06). Never a raw password, never a fast hash.
    password_hash: Mapped[str] = mapped_column(Text, nullable=False)
    is_active: Mapped[bool] = mapped_column(Boolean, nullable=False, default=True)
    created_at: Mapped[dt.datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )
    #: Bumped on password change/reset so every existing session dies (C-09).
    session_epoch: Mapped[int] = mapped_column(Integer, nullable=False, default=0)

    documents: Mapped[list[Document]] = relationship(back_populates="owner")


class Document(Base):
    __tablename__ = "documents"

    id: Mapped[uuid.UUID] = _uuid_pk()
    owner_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), nullable=False, index=True
    )
    #: Sanitised for display only. Never used to build a filesystem path.
    original_filename: Mapped[str] = mapped_column(String(255), nullable=False)
    #: Non-guessable key, unrelated to the uploaded name (C-30).
    blob_key: Mapped[str] = mapped_column(String(128), unique=True, nullable=False)
    content_type: Mapped[str] = mapped_column(String(64), nullable=False)
    byte_size: Mapped[int] = mapped_column(Integer, nullable=False)
    sha256: Mapped[str] = mapped_column(String(64), nullable=False)
    width: Mapped[int] = mapped_column(Integer, nullable=False)
    height: Mapped[int] = mapped_column(Integer, nullable=False)
    status: Mapped[DocumentStatus] = mapped_column(
        Enum(
            DocumentStatus,
            name="document_status",
            # Store the lowercase values, not the Python member names, so raw SQL and
            # the API contract agree.
            values_callable=lambda e: [m.value for m in e],
        ),
        nullable=False,
        default=DocumentStatus.PENDING,
    )
    uploaded_at: Mapped[dt.datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )
    #: Q-5: 90 days for originals. NOT NULL so no upload can escape retention.
    originals_expire_at: Mapped[dt.datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, index=True
    )
    deleted_at: Mapped[dt.datetime | None] = mapped_column(DateTime(timezone=True))

    owner: Mapped[User] = relationship(back_populates="documents")
    consent: Mapped[ConsentRecord | None] = relationship(
        back_populates="document", uselist=False, cascade="all, delete-orphan"
    )
    transcriptions: Mapped[list[Transcription]] = relationship(
        back_populates="document", cascade="all, delete-orphan"
    )

    __table_args__ = (
        CheckConstraint("byte_size > 0", name="ck_documents_size_positive"),
        CheckConstraint("width > 0 AND height > 0", name="ck_documents_dims_positive"),
        Index("ix_documents_owner_status", "owner_id", "status"),
    )


class ConsentRecord(Base):
    """Consent and lawful basis for one document (C-40).

    ``eligible_for_training`` is generated by Postgres, not set by the application.
    That is deliberate: Q-2 requires that a minor's document can never reach a training
    set, and a generated column makes that a schema property instead of a code path
    someone can forget.
    """

    __tablename__ = "consent_records"

    id: Mapped[uuid.UUID] = _uuid_pk()
    document_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("documents.id", ondelete="CASCADE"), nullable=False, unique=True
    )
    lawful_basis: Mapped[LawfulBasis] = mapped_column(
        Enum(
            LawfulBasis,
            name="lawful_basis",
            values_callable=lambda e: [m.value for m in e],
        ),
        nullable=False,
    )
    notice_version: Mapped[str] = mapped_column(String(32), nullable=False)
    #: Separate, explicit opt-in. Never bundled with consent to process the document
    #: for the user's own transcription (Q-2).
    research_opt_in: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False)
    #: Defaults to True: unknown means excluded. Q-2 says do not process minors' data
    #: on an assumption, so the safe value is the default.
    subject_is_minor: Mapped[bool] = mapped_column(Boolean, nullable=False, default=True)
    consented_at: Mapped[dt.datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )

    #: Generated by the database. There is no setter.
    eligible_for_training: Mapped[bool] = mapped_column(
        Boolean,
        Computed("research_opt_in AND NOT subject_is_minor", persisted=True),
        nullable=False,
    )

    document: Mapped[Document] = relationship(back_populates="consent")

    __table_args__ = (UniqueConstraint("document_id", name="uq_consent_document"),)


class Transcription(Base):
    __tablename__ = "transcriptions"

    id: Mapped[uuid.UUID] = _uuid_pk()
    document_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("documents.id", ondelete="CASCADE"), nullable=False, index=True
    )
    schema_version: Mapped[str] = mapped_column(String(16), nullable=False, default="1")
    #: JSON is the source of truth; markdown is derived from it (ADR-0009).
    structured: Mapped[dict[str, object]] = mapped_column(JSONB, nullable=False)
    markdown: Mapped[str] = mapped_column(Text, nullable=False)
    #: C-41: PII redaction has run. Must be true before anything crosses TB-06.
    pii_redacted: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False)
    #: "stub" output is not a real transcription and must never be presented as one.
    pipeline_mode: Mapped[str] = mapped_column(String(16), nullable=False)
    contains_stub_stages: Mapped[bool] = mapped_column(Boolean, nullable=False, default=True)
    #: AES-256-GCM ciphertext of the transcription (control C-37). Populated when
    #: field encryption is enabled; the plaintext column is then left empty.
    encrypted_text: Mapped[str | None] = mapped_column(Text)
    created_at: Mapped[dt.datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )

    document: Mapped[Document] = relationship(back_populates="transcriptions")


class PasswordResetToken(Base):
    """Single-use, short-lived, hashed-at-rest reset token (control C-10, threat T-10).

    The plaintext token exists only in the email. ``token_hash`` is SHA-256 of it, so a
    database read yields nothing usable. ``consumed_at`` is set atomically on use.
    """

    __tablename__ = "password_reset_tokens"

    id: Mapped[uuid.UUID] = _uuid_pk()
    user_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), nullable=False, index=True
    )
    token_hash: Mapped[str] = mapped_column(String(64), nullable=False, unique=True)
    expires_at: Mapped[dt.datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, index=True
    )
    consumed_at: Mapped[dt.datetime | None] = mapped_column(DateTime(timezone=True))
    created_at: Mapped[dt.datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )


class AuditEvent(Base):
    """Security event log (C-38). Never contains secrets or document content."""

    __tablename__ = "audit_events"

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True, autoincrement=True)
    ts: Mapped[dt.datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now(), index=True
    )
    actor_user_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("users.id", ondelete="SET NULL")
    )
    event_type: Mapped[str] = mapped_column(String(64), nullable=False, index=True)
    outcome: Mapped[str] = mapped_column(String(16), nullable=False)
    source_ip: Mapped[str | None] = mapped_column(INET)
    detail: Mapped[dict[str, object]] = mapped_column(JSONB, nullable=False, default=dict)
