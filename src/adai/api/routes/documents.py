"""Document upload, retrieval and deletion.

The upload path is the highest-risk surface in the application (threat T-03). Order of
operations is: authenticate, size-check, validate+re-encode (C-27/28/29), persist the
sanitised bytes only, record consent (C-40), then enqueue. The original bytes are never
written to disk.
"""

from __future__ import annotations

import datetime as dt
import json
from pathlib import Path
from typing import Annotated, Any

from fastapi import APIRouter, Depends, File, Form, HTTPException, UploadFile, status
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from adai.api.deps import current_user, owned_document, require_csrf
from adai.config import Settings, get_settings
from adai.db import get_session
from adai.logging import get_logger
from adai.models import (
    ConsentRecord,
    Document,
    DocumentStatus,
    LawfulBasis,
    Transcription,
    User,
)
from adai.queue import enqueue_document
from adai.schemas import ConsentInput, DocumentOut, StageOut, TranscriptionOut
from adai.security.audit import record_audit_event
from adai.security.crypto import DecryptionError, decrypt_field, derive_key
from adai.security.uploads import UploadRejectedError, validate_and_sanitise

# require_csrf runs on every route here; it is a no-op for safe methods and for
# requests with no session cookie (control C-08).
router = APIRouter(prefix="/documents", tags=["documents"], dependencies=[Depends(require_csrf)])
log = get_logger("adai.documents")


def _blob_path(root: str, blob_key: str) -> Path:
    """Resolve a blob path, refusing anything that escapes the blob root.

    blob_key is generated by us (token_urlsafe) and never user-controlled, but the
    containment check is cheap and this is the function a future refactor would misuse.
    """
    base = Path(root).resolve()
    target = (base / blob_key).resolve()
    if not target.is_relative_to(base):
        raise ValueError("blob key escapes blob root")
    return target


@router.post("", response_model=DocumentOut, status_code=status.HTTP_201_CREATED)
async def upload_document(
    session: Annotated[AsyncSession, Depends(get_session)],
    settings: Annotated[Settings, Depends(get_settings)],
    user: Annotated[User, Depends(current_user)],
    file: Annotated[UploadFile, File()],
    research_opt_in: Annotated[bool, Form()] = False,
    subject_is_minor: Annotated[bool, Form()] = True,
    notice_version: Annotated[str, Form()] = "v1",
) -> Document:
    raw = await file.read(settings.max_upload_bytes + 1)
    if len(raw) > settings.max_upload_bytes:
        raise HTTPException(
            status_code=status.HTTP_413_REQUEST_ENTITY_TOO_LARGE, detail="upload too large"
        )

    try:
        clean = validate_and_sanitise(
            raw,
            max_bytes=settings.max_upload_bytes,
            max_pixels=settings.max_image_pixels,
            max_dimension=settings.max_image_dimension,
            allowed_types=settings.allowed_upload_types,
        )
    except UploadRejectedError as exc:
        await record_audit_event(
            session,
            event_type="upload_rejected",
            outcome=exc.code,
            actor_user_id=user.id,
            detail={"code": exc.code},
        )
        log.info("upload_rejected", code=exc.code)
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_CONTENT, detail=exc.reason
        ) from exc

    # Validate the consent payload through the same strict schema used elsewhere.
    consent_input = ConsentInput(
        notice_version=notice_version,
        research_opt_in=research_opt_in,
        subject_is_minor=subject_is_minor,
    )

    path = _blob_path(settings.blob_root, clean.blob_key)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(clean.data)

    now = dt.datetime.now(dt.UTC)
    document = Document(
        owner_id=user.id,
        original_filename=Path(file.filename or "upload").name[:255],
        blob_key=clean.blob_key,
        content_type=clean.content_type,
        byte_size=len(clean.data),
        sha256=clean.sha256,
        width=clean.width,
        height=clean.height,
        status=DocumentStatus.PENDING,
        originals_expire_at=now + dt.timedelta(days=settings.original_retention_days),
    )
    session.add(document)
    await session.flush()

    session.add(
        ConsentRecord(
            document_id=document.id,
            lawful_basis=LawfulBasis(consent_input.lawful_basis),
            notice_version=consent_input.notice_version,
            research_opt_in=consent_input.research_opt_in,
            subject_is_minor=consent_input.subject_is_minor,
        )
    )
    await record_audit_event(
        session,
        event_type="upload_accepted",
        outcome="success",
        actor_user_id=user.id,
        detail={"document_id": str(document.id)},
    )
    # Enqueue OUTSIDE the request's own work: the handler returns as soon as the
    # document is persisted, and the pipeline runs in the worker (ADR-0011).
    job_id = await enqueue_document(str(document.id))
    log.info("upload_accepted", document_id=str(document.id), job_id=job_id)
    return document


@router.get("", response_model=list[DocumentOut])
async def list_documents(
    session: Annotated[AsyncSession, Depends(get_session)],
    user: Annotated[User, Depends(current_user)],
) -> list[Document]:
    stmt = (
        select(Document)
        .where(Document.owner_id == user.id, Document.deleted_at.is_(None))
        .order_by(Document.uploaded_at.desc())
        .limit(200)
    )
    return list((await session.execute(stmt)).scalars())


@router.get("/{document_id}", response_model=DocumentOut)
async def get_document(document: Annotated[Document, Depends(owned_document)]) -> Document:
    return document


@router.get("/{document_id}/transcription", response_model=TranscriptionOut)
async def get_transcription(
    document: Annotated[Document, Depends(owned_document)],
    session: Annotated[AsyncSession, Depends(get_session)],
    settings: Annotated[Settings, Depends(get_settings)],
) -> TranscriptionOut:
    stmt = (
        select(Transcription)
        .where(Transcription.document_id == document.id)
        .order_by(Transcription.created_at.desc())
        .limit(1)
    )
    row = (await session.execute(stmt)).scalar_one_or_none()
    if row is None:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="not found")
    # structured JSONB holds provenance only; the transcription itself lives encrypted
    # at rest (control C-37) and is decrypted here for the owner of the document.
    structured: dict[str, Any] = row.structured if isinstance(row.structured, dict) else {}
    markdown = row.markdown
    regions: list[dict[str, object]] = []
    if row.encrypted_text:
        try:
            payload = json.loads(
                decrypt_field(
                    row.encrypted_text, derive_key(settings.secret_key.get_secret_value())
                )
            )
        except (DecryptionError, json.JSONDecodeError) as exc:
            log.error("transcription_decrypt_failed", document_id=str(document.id))
            raise HTTPException(
                status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
                detail="transcription unavailable",
            ) from exc
        markdown = str(payload.get("markdown", ""))
        raw_regions = payload.get("regions", [])
        regions = (
            [r for r in raw_regions if isinstance(r, dict)] if isinstance(raw_regions, list) else []
        )
    raw_stages = structured.get("stages", [])
    # Project onto StageOut's declared fields. The stored stage record carries
    # internals such as duration_ms that the response schema deliberately omits
    # (control C-21), and StageOut forbids extras.
    stage_fields = set(StageOut.model_fields)
    stages = (
        [
            StageOut(**{k: v for k, v in stage.items() if k in stage_fields})
            for stage in raw_stages
            if isinstance(stage, dict)
        ]
        if isinstance(raw_stages, list)
        else []
    )
    return TranscriptionOut(
        document_id=document.id,
        schema_version=row.schema_version,
        markdown=markdown,
        regions=regions,
        contains_stub_stages=row.contains_stub_stages,
        stages=stages,
        pii_redacted=row.pii_redacted,
    )


@router.delete("/{document_id}", status_code=status.HTTP_204_NO_CONTENT)
async def delete_document(
    document: Annotated[Document, Depends(owned_document)],
    session: Annotated[AsyncSession, Depends(get_session)],
    settings: Annotated[Settings, Depends(get_settings)],
) -> None:
    """User-initiated deletion (C-42, Q-5): purges the blob, not just the row."""
    try:
        _blob_path(settings.blob_root, document.blob_key).unlink(missing_ok=True)
    except ValueError:  # pragma: no cover - defensive
        log.warning("blob_path_rejected", document_id=str(document.id))
    document.deleted_at = dt.datetime.now(dt.UTC)
    document.status = DocumentStatus.DELETED
    await record_audit_event(
        session,
        event_type="document_deleted",
        outcome="success",
        actor_user_id=document.owner_id,
        detail={"document_id": str(document.id)},
    )
